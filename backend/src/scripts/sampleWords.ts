const toWords = (level: LearningLevel, steps: Row[][]) =>
  steps.flatMap((rows, s) =>
    rows.map(([pron, entry, means, parts], i) => ({
      origin_entry_id: `sample-${level}-${s + 1}-${i + 1}`,
      entry,
      pron,
      level,
      step: s + 1,
      means: means.split(', '),
      parts: [parts],
    }))
  );

